CREATE TABLE fireworks_jurisdiction_policies (
    id VARCHAR(36) NOT NULL,
    scope_key VARCHAR(240) NOT NULL,
    state_code VARCHAR(10) NOT NULL,
    district VARCHAR(100) NULL,
    postal_code VARCHAR(10) NULL,
    sale_allowed BOOLEAN NOT NULL,
    delivery_allowed BOOLEAN NOT NULL,
    transport_allowed BOOLEAN NOT NULL,
    storage_allowed BOOLEAN NOT NULL,
    effective_from TIMESTAMP(6) NOT NULL,
    effective_until TIMESTAMP(6) NULL,
    source_reference VARCHAR(500) NOT NULL,
    legal_notes VARCHAR(2000) NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'DRAFT',
    created_by VARCHAR(255) NOT NULL,
    reviewed_by VARCHAR(255) NULL,
    reviewed_at TIMESTAMP(6) NULL,
    revoked_by VARCHAR(255) NULL,
    revoked_at TIMESTAMP(6) NULL,
    revocation_reason VARCHAR(500) NULL,
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    CONSTRAINT uk_fireworks_policy_scope_start UNIQUE (scope_key, effective_from),
    CONSTRAINT chk_fireworks_policy_status CHECK (status IN ('DRAFT', 'APPROVED', 'REVOKED')),
    CONSTRAINT chk_fireworks_policy_period CHECK (effective_until IS NULL OR effective_until > effective_from),
    INDEX idx_fireworks_policy_scope_status (scope_key, status, effective_from)
);
